package com.labloop.web;

import java.io.*;
import java.net.*;
import java.sql.*;
import java.util.*;
import com.sun.net.httpserver.*;

public class LabLoopApplication {
    static Connection conn;

    public static void main(String[] args) throws Exception {
        // 1. Database Connection & URI Parsing (Handles Local H2 and Render PostgreSQL)
        String dbUrl = System.getenv("DATABASE_URL");
        String user = "sa";
        String pass = "";

        if (dbUrl == null) {
            dbUrl = "jdbc:h2:mem:labloop;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
        } else if (dbUrl.startsWith("postgres://")) {
            // Render passes raw postgres URI, JDBC needs it converted
            URI uri = new URI(dbUrl);
            user = uri.getUserInfo().split(":")[0];
            pass = uri.getUserInfo().split(":")[1];
            dbUrl = "jdbc:postgresql://" + uri.getHost() + ":" + uri.getPort() + uri.getPath() + "?sslmode=require";
        }

        conn = DriverManager.getConnection(dbUrl, user, pass);
        initDb(); // Create tables using pure SQL

        // 2. Start built-in Java HTTP Server
        String portEnv = System.getenv("PORT");
        int port = portEnv != null ? Integer.parseInt(portEnv) : 8080;
        HttpServer server = HttpServer.create(new InetSocketAddress(port), 0);

        // 3. Map Endpoints
        server.createContext("/api/equipment", new ApiHandler());
        server.createContext("/", new StaticHandler());

        server.setExecutor(null);
        server.start();
        System.out.println("Pure Java Server started on port " + port);
    }

    // --- DATABASE INITIALIZATION ---
    static void initDb() throws SQLException {
        Statement st = conn.createStatement();
        st.execute("CREATE TABLE IF NOT EXISTS equipment (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(30) UNIQUE NOT NULL, name VARCHAR(100) NOT NULL, category VARCHAR(60), status VARCHAR(20) NOT NULL, condition_state VARCHAR(20) NOT NULL, location VARCHAR(80))");
        st.execute("CREATE TABLE IF NOT EXISTS activity (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, equipment_id BIGINT, action VARCHAR(30), person VARCHAR(80), note VARCHAR(255), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        
        ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM equipment");
        rs.next();
        if (rs.getInt(1) == 0) {
            st.execute("INSERT INTO equipment(code,name,category,status,condition_state,location) VALUES ('MIC-001','Compound Microscope','Optics','AVAILABLE','GOOD','Cabinet A')");
            st.execute("INSERT INTO equipment(code,name,category,status,condition_state,location) VALUES ('MTR-001','Digital Multimeter','Electronics','AVAILABLE','GOOD','Shelf B')");
        }
    }

    // --- API HANDLER (Replaces Spring @RestController) ---
    static class ApiHandler implements HttpHandler {
        public void handle(HttpExchange t) throws IOException {
            String method = t.getRequestMethod();
            String path = t.getRequestURI().getPath();
            String response = "{\"ok\":true}";
            int statusCode = 200;

            try {
                if (path.equals("/api/equipment") && method.equals("GET")) {
                    Statement stmt = conn.createStatement();
                    ResultSet rs = stmt.executeQuery("SELECT * FROM equipment ORDER BY id DESC");
                    response = resultSetToJson(rs);

                } else if (path.equals("/api/equipment") && method.equals("POST")) {
                    Map<String, String> body = parseJsonBody(t);
                    PreparedStatement ps = conn.prepareStatement("INSERT INTO equipment(code, name, category, status, condition_state, location) VALUES (?,?,?,?,?,?)");
                    ps.setString(1, body.get("code"));
                    ps.setString(2, body.get("name"));
                    ps.setString(3, body.get("category"));
                    ps.setString(4, body.get("status"));
                    ps.setString(5, body.get("condition"));
                    ps.setString(6, body.get("location"));
                    ps.executeUpdate();

                } else if (path.matches("/api/equipment/\\d+") && method.equals("PUT")) {
                    long id = Long.parseLong(path.split("/")[3]);
                    Map<String, String> body = parseJsonBody(t);
                    PreparedStatement ps = conn.prepareStatement("UPDATE equipment SET name=?, category=?, status=?, condition_state=?, location=? WHERE id=?");
                    ps.setString(1, body.get("name"));
                    ps.setString(2, body.get("category"));
                    ps.setString(3, body.get("status"));
                    ps.setString(4, body.get("condition"));
                    ps.setString(5, body.get("location"));
                    ps.setLong(6, id);
                    ps.executeUpdate();

                } else if (path.matches("/api/equipment/\\d+") && method.equals("DELETE")) {
                    long id = Long.parseLong(path.split("/")[3]);
                    PreparedStatement ps1 = conn.prepareStatement("DELETE FROM activity WHERE equipment_id=?");
                    ps1.setLong(1, id);
                    ps1.executeUpdate();
                    
                    PreparedStatement ps2 = conn.prepareStatement("DELETE FROM equipment WHERE id=?");
                    ps2.setLong(1, id);
                    ps2.executeUpdate();

                } else if (path.matches("/api/equipment/\\d+/(borrow|return|inspect)") && method.equals("POST")) {
                    long id = Long.parseLong(path.split("/")[3]);
                    String action = path.split("/")[4];
                    Map<String, String> body = parseJsonBody(t);
                    
                    String status = action.equals("borrow") ? "BORROWED" : action.equals("return") ? "AVAILABLE" : "MAINTENANCE";
                    String condition = body.getOrDefault("condition", "GOOD");
                    
                    PreparedStatement ps1 = conn.prepareStatement("UPDATE equipment SET status=?, condition_state=? WHERE id=?");
                    ps1.setString(1, status);
                    ps1.setString(2, condition);
                    ps1.setLong(3, id);
                    ps1.executeUpdate();
                    
                    PreparedStatement ps2 = conn.prepareStatement("INSERT INTO activity (equipment_id, action, person, note) VALUES (?, ?, ?, ?)");
                    ps2.setLong(1, id);
                    ps2.setString(2, action.toUpperCase());
                    ps2.setString(3, "System User");
                    ps2.setString(4, "Condition logged as " + condition);
                    ps2.executeUpdate();

                } else if (path.matches("/api/equipment/\\d+/activity") && method.equals("GET")) {
                    long id = Long.parseLong(path.split("/")[3]);
                    PreparedStatement ps = conn.prepareStatement("SELECT * FROM activity WHERE equipment_id=? ORDER BY created_at DESC");
                    ps.setLong(1, id);
                    ResultSet rs = ps.executeQuery();
                    response = resultSetToJson(rs);
                }
            } catch (Exception e) {
                e.printStackTrace();
                response = "{\"error\":\"" + e.getMessage() + "\"}";
                statusCode = 500;
            }

            t.getResponseHeaders().set("Content-Type", "application/json");
            byte[] bytes = response.getBytes();
            t.sendResponseHeaders(statusCode, bytes.length);
            OutputStream os = t.getResponseBody();
            os.write(bytes);
            os.close();
        }
    }

    // --- STATIC FILES HANDLER (Serves HTML, CSS, JS) ---
    static class StaticHandler implements HttpHandler {
        public void handle(HttpExchange t) throws IOException {
            String path = t.getRequestURI().getPath();
            if (path.equals("/")) path = "/index.html";
            
            InputStream is = LabLoopApplication.class.getResourceAsStream("/static" + path);
            if (is == null) {
                t.sendResponseHeaders(404, -1);
                return;
            }
            
            byte[] bytes = is.readAllBytes();
            if (path.endsWith(".html")) t.getResponseHeaders().set("Content-Type", "text/html");
            else if (path.endsWith(".css")) t.getResponseHeaders().set("Content-Type", "text/css");
            else if (path.endsWith(".js")) t.getResponseHeaders().set("Content-Type", "application/javascript");
            
            t.sendResponseHeaders(200, bytes.length);
            OutputStream os = t.getResponseBody();
            os.write(bytes);
            os.close();
        }
    }

    // --- HELPER: Manual JSON Parser (No external libraries needed) ---
    static Map<String, String> parseJsonBody(HttpExchange t) throws IOException {
        String json = new String(t.getRequestBody().readAllBytes());
        Map<String, String> map = new HashMap<>();
        json = json.replaceAll("[{}\"]", ""); 
        String[] pairs = json.split(",");
        for (String pair : pairs) {
            String[] kv = pair.split(":", 2);
            if (kv.length == 2) map.put(kv[0].trim(), kv[1].trim());
        }
        return map;
    }

    // --- HELPER: Convert JDBC ResultSet to JSON String ---
    static String resultSetToJson(ResultSet rs) throws SQLException {
        ResultSetMetaData md = rs.getMetaData();
        int cols = md.getColumnCount();
        StringBuilder sb = new StringBuilder("[");
        while (rs.next()) {
            if (sb.length() > 1) sb.append(",");
            sb.append("{");
            for (int i = 1; i <= cols; i++) {
                if (i > 1) sb.append(",");
                String val = rs.getString(i);
                val = val == null ? "" : val.replace("\"", "\\\"");
                sb.append("\"").append(md.getColumnName(i).toLowerCase()).append("\":\"").append(val).append("\"");
            }
            sb.append("}");
        }
        sb.append("]");
        return sb.toString();
    }
}